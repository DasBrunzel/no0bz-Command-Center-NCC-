"""Generate readability overrides for the legacy dashboard stylesheets.

The older stylesheets use 8-11 px labels, wide letter-spacing and accent glows
in hundreds of rules. Instead of editing every rule by hand, this script reads
them and writes frontend/src/design-readability.css, which design.css imports.
Re-run it after changing index.css or concept/styles.css.
"""
from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCES = [ROOT / "frontend/src/index.css", ROOT / "frontend/src/concept/styles.css"]
TARGET = ROOT / "frontend/src/design-readability.css"
RULE = re.compile(r"([^{}@]+)\{([^{}]*)\}")
FONT = re.compile(r"font-size\s*:\s*([\d.]+)px")
SPACING = re.compile(r"letter-spacing\s*:\s*([\d.]+)em")
GLOW = re.compile(r"box-shadow\s*:[^;]*(var\(--(mint|accent)\)|rgba\(var\(--accent-rgb\))")


def _selectors(raw: str) -> list[str]:
    # Theme-specific rules belong to themes that no longer exist.
    return [s.strip() for s in raw.split(",") if s.strip() and "data-theme" not in s]


def main() -> None:
    small: list[str] = []
    medium: list[str] = []
    spaced: list[str] = []
    glows: list[str] = []
    for source in SOURCES:
        css = re.sub(r"/\*.*?\*/", "", source.read_text(encoding="utf-8"), flags=re.S)
        for selector_text, body in RULE.findall(css):
            selectors = _selectors(selector_text)
            if not selectors:
                continue
            if size := FONT.search(body):
                value = float(size.group(1))
                if value < 12:
                    small += selectors
                elif value < 13:
                    medium += selectors
            if (spacing := SPACING.search(body)) and float(spacing.group(1)) > 0.04:
                spaced += selectors
            if GLOW.search(body):
                glows += selectors

    def block(selectors: list[str], declarations: str) -> str:
        unique = sorted(dict.fromkeys(selectors))
        return ",\n".join(unique) + " {\n  " + declarations + "\n}\n" if unique else ""

    TARGET.write_text(
        "/* Generated by scripts/generate_dashboard_readability_css.py. Do not edit. */\n"
        + block(small, "font-size: max(12px, 0.8rem);")
        + block(medium, "font-size: 13px;")
        + block(spaced, "letter-spacing: 0.01em;")
        + block(glows, "box-shadow: none;"),
        encoding="utf-8",
    )
    print(f"{len(small)} small, {len(medium)} medium, {len(spaced)} spaced, {len(glows)} glow selectors")


if __name__ == "__main__":
    main()
